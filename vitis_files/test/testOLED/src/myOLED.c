// ---------- 内部字符绘制函数（带字号参数）----------
static void draw_char_size(u8 x, u8 y, char ch, OLED_FontSize size) {
    const unsigned char *pChar;
    u8 width, height, bytesPerChar;
    u8 col, row, sec, byteIdx;

    switch (size) {
        case FONT_6X8:
            width = 6; height = 8; bytesPerChar = 6;
            break;
        case FONT_8X16:
            width = 8; height = 16; bytesPerChar = 16;
            break;
        case FONT_12X24:
            width = 12; height = 24; bytesPerChar = 36;
            break;
        default:
            return;
    }

    if (ch < ' ' || ch > '~') ch = ' ';
    switch (size) {
        case FONT_6X8:   pChar = &F6X8[(ch - ' ') * bytesPerChar];   break;
        case FONT_8X16:  pChar = &F8X16[(ch - ' ') * bytesPerChar];  break;
        case FONT_12X24: pChar = &F12X24[(ch - ' ') * bytesPerChar]; break;
        default: return;
    }

    for (col = 0; col < width; col++) {
        if (x + col >= OLED_WIDTH) break;
        u8 numSections = (height + 7) / 8;
        u8 currentY = y;
        for (sec = 0; sec < numSections; sec++) {
            byteIdx = col + sec * width;
            u8 byteVal = pChar[byteIdx];
            u8 rowsInSection = 8;
            if ((sec == numSections - 1) && (height % 8 != 0))
                rowsInSection = height % 8;
            for (row = 0; row < rowsInSection; row++) {
                if (byteVal & (1 << row))
                    oled_set_pixel(x + col, currentY + row, 1);
                else
                    oled_set_pixel(x + col, currentY + row, 0);
            }
            currentY += 8;
        }
    }
}

// ---------- 对外字符显示函数（使用全局字号）----------
void oled_show_char(u8 x, u8 y, char ch) {
    draw_char_size(x, y, ch, current_font);
}

void oled_show_string(u8 x, u8 y, const char *str) {
    u8 width;
    switch (current_font) {
        case FONT_6X8:   width = 6; break;
        case FONT_8X16:  width = 8; break;
        case FONT_12X24: width = 12; break;
        default: return;
    }
    while (*str) {
        draw_char_size(x, y, *str++, current_font);
        x += width;
        if (x + width > OLED_WIDTH) break;
    }
}

// ---------- 设置全局字号 ----------
void oled_set_size(OLED_FontSize size) {
    current_font = size;
}
