// 显存数组（128×64 像素 = 1024 字节）
static u8 vram[OLED_WIDTH * OLED_PAGES];

static OLED_FontSize current_font = FONT_8X16;

// ---------- 底层 SPI 发送（复用已有函数）----------
static void spi_send_byte(u8 data, u8 dc){

    while(MYOLED_mReadReg(XPAR_MYOLED_0_BASEADDR, MYOLED_S00_AXI_SLV_REG3_OFFSET));

    MYOLED_mWriteReg(XPAR_MYOLED_0_BASEADDR, MYOLED_S00_AXI_SLV_REG2_OFFSET, dc?1:0);

    MYOLED_mWriteReg(XPAR_MYOLED_0_BASEADDR, MYOLED_S00_AXI_SLV_REG1_OFFSET, data);

    MYOLED_mWriteReg(XPAR_MYOLED_0_BASEADDR, MYOLED_S00_AXI_SLV_REG0_OFFSET, 1);
    usleep(1);
    MYOLED_mWriteReg(XPAR_MYOLED_0_BASEADDR, MYOLED_S00_AXI_SLV_REG0_OFFSET, 0);
}

void oled_write_cmd(u8 cmd) {
    spi_send_byte(cmd, 0);
}

void oled_write_data(u8 data) {
    spi_send_byte(data, 1);
}

// ---------- OLED 初始化序列 ----------
void oled_init(void) {
    // 等待上电稳定（若已在 main 中延时，可省略）
    oled_write_cmd(OLED_CMD_DISPLAY_OFF);          // AE: 关闭显示
    oled_write_cmd(OLED_CMD_SET_DISPLAY_CLOCK_DIV);// D5
    oled_write_cmd(0x80);                          // 分频因子/振荡器频率
    oled_write_cmd(OLED_CMD_SET_MUX_RATIO);        // A8
    oled_write_cmd(0x3F);                          // 64 行
    oled_write_cmd(OLED_CMD_SET_DISPLAY_OFFSET);   // D3
    oled_write_cmd(0x00);                          // 偏移 0
    oled_write_cmd(OLED_CMD_SET_START_LINE | 0x00);// 40: 起始行 0
    oled_write_cmd(OLED_CMD_CHARGE_PUMP);          // 8D
    oled_write_cmd(0x14);                          // 使能电荷泵
    oled_write_cmd(OLED_CMD_SET_MEM_ADDR_MODE);    // 20
    oled_write_cmd(0x00);                          // 水平寻址模式
    oled_write_cmd(OLED_CMD_SET_SEG_REMAP | 0x01); // A1: 列地址 127 映射到 SEG0
    oled_write_cmd(OLED_CMD_SET_COM_SCAN_DIR | 0x08); // C8: COM 扫描方向从下到上
    oled_write_cmd(OLED_CMD_SET_COM_PINS);         // DA
    oled_write_cmd(0x12);                          // 顺序 COM 配置
    oled_write_cmd(OLED_CMD_SET_CONTRAST);         // 81
    oled_write_cmd(0xCF);                          // 对比度值
    oled_write_cmd(OLED_CMD_SET_PRECHARGE);        // D9
    oled_write_cmd(0xF1);                          // 预充电周期
    oled_write_cmd(OLED_CMD_SET_VCOM_DESELECT);    // DB
    oled_write_cmd(0x40);                          // VCOMH 电压
    oled_write_cmd(OLED_CMD_NORMAL_DISPLAY);       // A6
    oled_write_cmd(0x2E);                          // 停止滚动
    oled_write_cmd(OLED_CMD_DISPLAY_ON);           // AF: 开启显示
}

// ---------- 设置页与列（用于手动控制）----------
void oled_set_pos(u8 page, u8 col) {
    oled_write_cmd(0xB0 | (page & 0x07));          // 设置页地址
    oled_write_cmd(0x00 | (col & 0x0F));           // 列低 4 位
    oled_write_cmd(0x10 | ((col >> 4) & 0x0F));    // 列高 4 位
}

// ---------- 全屏填充（清屏或全亮）----------
void oled_fill(u8 pattern) {
    u8 page, col;
    for (page = 0; page < OLED_PAGES; page++) {
        oled_set_pos(page, 0);
        for (col = 0; col < OLED_WIDTH; col++) {
            oled_write_data(pattern);
        }
    }
}

void oled_clear(void) {
    oled_fill(0x00);
}

// ---------- 像素操作（基于显存）----------
void oled_set_pixel(u8 x, u8 y, u8 color) {
    if (x >= OLED_WIDTH || y >= OLED_HEIGHT) return;
    u8 page = y / 8;
    u8 bit = y % 8;
    if (color)
        vram[page * OLED_WIDTH + x] |= (1 << bit);
    else
        vram[page * OLED_WIDTH + x] &= ~(1 << bit);
}

// ---------- 刷新显存到 OLED（连续写）----------
void oled_refresh(void) {
    u8 page, col;
    // 设置寻址范围：全部列和全部页
    oled_write_cmd(OLED_CMD_SET_COL_ADDR);
    oled_write_cmd(0);
    oled_write_cmd(OLED_WIDTH - 1);
    oled_write_cmd(OLED_CMD_SET_PAGE_ADDR);
    oled_write_cmd(0);
    oled_write_cmd(OLED_PAGES - 1);

    // 连续写入显存数据
    for (page = 0; page < OLED_PAGES; page++) {
        for (col = 0; col < OLED_WIDTH; col++) {
            oled_write_data(vram[page * OLED_WIDTH + col]);
        }
    }
}

